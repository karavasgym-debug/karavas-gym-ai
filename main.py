from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
import openai
import os

app = FastAPI()

# Ρυθμίσεις CORS για να μπορεί το Streamlit να μιλάει με το API
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Παίρνουμε το API Key της OpenAI από τα Environment Variables του Render
openai.api_key = os.getenv("OPENAI_API_KEY")

@app.post("/generate-plan")
async def generate_plan(data: dict):
    gender = data.get("gender")
    weight = data.get("weight")
    height = data.get("height")
    age = data.get("age")
    goal = data.get("goal")
    activity_level = data.get("activity_level")
    diet_type = data.get("diet_type")
    allergies = data.get("allergies", "Καμία")
    include_supplements = data.get("include_supplements", False)
    activities = data.get("activities", [])

    # Δυναμικό χτίσιμο της εξειδίκευσης ανά άθλημα
    sport_context = ""

    if "Πολεμικές Τέχνες / BJJ" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Πολεμικές Τέχνες / Brazilian Jiu-Jitsu / MMA.
        - ΦΥΣΙΟΛΟΓΙΑ: Υψηλές απαιτήσεις σε εκρηκτικότητα, γλυκολυτική αντοχή, ισομετρική δύναμη και ταχεία αποκατάσταση των αρθρώσεων.
        - ΟΔΗΓΙΕΣ: Δώσε έμφαση σε αντιφλεγμονώδεις τροφές (ωμέγα-3 λιπαρά, κουρκουμάς, μούρα) για την καταπόνηση από τα σπάρινγκ. Το pre-workout γεύμα πρέπει να είναι 2.5 ώρες πριν, εύπεπτο, πλούσιο σε υδατάνθρακες και χαμηλό σε λιπαρά/ίνες για αποφυγή δυσφορίας στο τατάμι.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Ηλεκτρολύτες (υποχρεωτικά λόγω έντονης εφίδρωσης), Κρεατίνη (για εκρηκτικότητα στα takedowns), και Κολλαγόνο/Γλυκοζαμίνη για προστασία αρθρώσεων και συνδέσμων.
        """

    if "Γυμναστήριο (Βάρη)" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Προπόνηση με Αντιστάσεις / Bodybuilding / Powerlifting.
        - ΦΥΣΙΟΛΟΓΙΑ: Μυϊκή καταστροφή (microtears), ανάγκη για θετικό ισοζύγιο αζώτου, πρωτεϊνοσύνθεση και αναπλήρωση γλυκογόνου.
        - ΟΔΗΓΙΕΣ: Εξασφάλισε 1.8g - 2.2g πρωτεΐνης ανά κιλό σωματικού βάρους. Σχεδίασε ένα ισχυρό μεταπροπονητικό γεύμα (Post-workout) με γρήγορη πρωτεΐνη και απλό υδατάνθρακα για την ενεργοποίηση της οδού mTOR (μυϊκή ανάπτυξη).
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Πρωτεΐνη ορού γάλακτος (Whey), Κρεατίνη (Monohydrate για αύξηση της ATP δύναμης) και Essential Amino Acids (EAA).
        """

    if "Crossfit" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Crossfit / Λειτουργική Προπόνηση Υψηλής Έντασης (HIIT).
        - ΦΥΣΙΟΛΟΓΙΑ: Μεταβολική εξάντληση, ακραία κατανάλωση μυϊκού γλυκογόνου, συσσώρευση γαλακτικού οξέος.
        - ΟΔΗΓΙΕΣ: Υψηλή παροχή σύνθετων υδατανθράκων (βρώμη, γλυκοπατάτα, ρύζι) για γεμάτες αποθήκες ενέργειας πριν από τα WOD. Η πρωτεΐνη πρέπει να παραμείνει υψηλή (~1.8g/kg) για την προστασία του μυϊκού ιστού από την καταβολική φύση της προπόνησης.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Βήτα-Αλανίνη (για buffering του γαλακτικού οξέος), Ηλεκτρολύτες, και Κυκλική Δεξτρίνη (Cluster Dextrin) κατά τη διάρκεια της προπόνησης.
        """

    if "Τρέξιμο / Jogging" in activities or "Ποδηλασία" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Αθλήματα Αντοχής / Cardiorespiratory Endurance.
        - ΦΥΣΙΟΛΟΓΙΑ: Παρατεταμένη αερόβια οξείδωση, ανάγκη για μέγιστη οικονομία γλυκογόνου, κίνδυνος αφυδάτωσης και μυϊκού καταβολισμού.
        - ΟΔΗΓΙΕΣ: Η διατροφή πρέπει να κυριαρχείται από υδατάνθρακες (50-60% των συνολικών θερμίδων). Μέτρια πρωτεΐνη (~1.4g - 1.6g/kg). Έμφαση σε γεύματα που δεν προκαλούν γαστρεντερικές διαταραχές. 
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Ενεργειακά τζελ (Carbo-gels) για μεγάλες αποστάσεις, Μαγνήσιο (για αποφυγή κραμπών) και Ηλεκτρολύτες.
        """

    if "Ποδόσφαιρο" in activities or "Μπάσκετ" in activities or "Τένις" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Διαλειμματικά Αθλήματα / Ποδόσφαιρο, Μπάσκετ, Τένις.
        - ΦΥΣΙΟΛΟΓΙΑ: Εναλλαγή αερόβιας και αναερόβιας πίεσης (sprints, άλματα, αλλαγές κατεύθυνσης). Μεγάλη εξάντληση νευρικού συστήματος και γλυκογόνου.
        - ΟΔΗΓΙΕΣ: Στρατηγική λήψη υδατανθράκων πριν από τον αγώνα/προπόνηση για διατήρηση της συγκέντρωσης και της ταχύτητας. Επαρκή καλά λιπαρά για την προστασία του νευρικού συστήματος.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Καφεΐνη (πριν το ματς για πνευματική εγρήγορση), Ηλεκτρολύτες, και Κρεατίνη.
        """

    if "Κολύμβηση" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Κολύμβηση.
        - ΦΥΣΙΟΛΟΓΙΑ: Πλήρης ενεργοποίηση όλου του σώματος σε περιβάλλον αντίστασης νερού. Υψηλή θερμιδική δαπάνη λόγω θερμορύθμισης.
        - ΟΔΗΓΙΕΣ: Αυξημένες θερμίδες συντήρησης. Λόγω της οριζόντιας θέσης στο νερό, τα γεύματα πριν την προπόνηση πρέπει να είναι εξαιρετικά ελαφριά (π.χ. φρούτο ή μέλι) για την αποφυγή παλινδρόμησης.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Βιταμίνη C και D3 (λόγω έκθεσης σε χλώριο/κρύο), και BCAA κατά τη διάρκεια μεγάλων προπονήσεων.
        """

    if "Γιόγκα / Πιλάτες" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Yoga / Pilates.
        - ΦΥΣΙΟΛΟΓΙΑ: Έμφαση στη σταθερότητα του πυρήνα, την ελαστικότητα και τον έλεγχο της αναπνοής.
        - ΟΔΗΓΙΕΣ: Διατροφή πλούσια σε φυτικές ίνες, ελαφριές πρωτεΐνες (ψάρι, κοτόπουλο, όσπρια) που δεν φουσκώνουν το στομάχι, επιτρέποντας τις διατάσεις και τις αναστροφές.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Πράσινο τσάι και Μαγνήσιο (για χαλάρωση του νευρικού συστήματος και των μυών το βράδυ).
        """

    if "Πεζοπορία (Hiking)" in activities:
        sport_context += """
        - ΑΘΛΗΜΑ: Πεζοπορία / Hiking.
        - ΦΥΣΙΟΛΟΓΙΑ: Πολύωρη δραστηριότητα χαμηλής-μέτριας έντασης, σταθερή καύση λίπους, καταπόνηση γονάτων λόγω φορτίου.
        - ΟΔΗΓΙΕΣ: Έμφαση σε πυκνά θερμιδικά σνακ που μεταφέρονται εύκολα (ξηροί καρποί, αποξηραμένα φρούτα, μπάρες βρώμης, παστέλι). Σωστή ενυδάτωση κατά τη διάρκεια της διαδρομής.
        - ΣΥΜΠΛΗΡΩΜΑΤΑ (αν ζητηθούν): Ηλεκτρολύτες σε σκόνη, Μπάρες πρωτεΐνης/ενέργειας.
        """

    supplements_instruction = "Συμπεριέλαβε οπωσδήποτε μια ειδική ενότητα με προτάσεις για ασφαλή και νόμιμα συμπληρώματα διατροφής, αναφέροντας πότε και πώς να λαμβάνονται." if include_supplements else "Μην αναφέρεις καθόλου συμπληρώματα διατροφής."

    system_prompt = f"""
    Είσαι ο κορυφαίος Αθλητικός Διατροφολόγος του Karavas Gym Fighting & Fitness.
    Σχεδίασε ένα αυστηρά εξατομικευμένο 7ήμερο πλάνο διατροφής σε άπταιστα Ελληνικά με βάση τα εξής στοιχεία:
    - Φύλο: {gender}, Βάρος: {weight}kg, Ύψος: {height}cm, Ηλικία: {age}.
    - Στόχος: {goal}, Τύπος Διατροφής: {diet_type}, Αλλεργίες/Αποφυγές: {allergies}.

    ΕΞΕΙΔΙΚΕΥΜΕΝΕΣ ΑΘΛΗΤΙΚΕΣ ΟΔΗΓΙΕΣ ΓΙΑ ΤΙΣ ΔΡΑΣΤΗΡΙΟΤΗΤΕΣ ΤΟΥ ΧΡΗΣΤΗ:
    {sport_context}

    {supplements_instruction}

    Δομή του πλάνου:
    1. Ανάλυση Στόχου & Μακροθρεπτικών Συστατικών (Πρωτεΐνες, Υδατάνθρακες, Λίπη) ειδικά για τα αθλήματά του.
    2. Αναλυτικό 7ήμερο πρόγραμμα (Πρωινό, Δεκατιανό, Μεσημεριανό, Απογευματινό/Pre-workout, Βραδινό, Post-workout).
    3. Οδηγίες γύρω από την προπόνηση (Τι να τρώει πριν και μετά το τατάμι/γυμναστήριο).
    4. Ενότητα Συμπληρωμάτων (αν έχει ενεργοποιηθεί).
    5. Λίστα Super Market για όλη την εβδομάδα με ενδεικτικές τιμές σε Ευρώ.
    """

    try:
        # Χρήση του νέου API call της OpenAI
        client = openai.OpenAI()
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": "Παρακαλώ δημιούργησε το εξειδικευμένο πλάνο διατροφής μου."}
            ],
            temperature=0.7
        )
        plan_text = response.choices[0].message.content
        return {"plan": plan_text}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
